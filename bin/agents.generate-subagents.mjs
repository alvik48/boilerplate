#!/usr/bin/env node
//
// Generate per-tool subagent definitions from the neutral sources in
// .agents/agents.
//
// Claude Code reads .claude/agents/<name>.md   -- YAML frontmatter + Markdown body.
// Codex      reads .codex/agents/<name>.toml   -- flat TOML, body as developer_instructions.
//
// The two formats are incompatible, so unlike .agents/skills this cannot be a
// symlink; see bin/agents.link-skills.sh for the case that can.
//
// .claude/ and .codex/ are gitignored, so output is rebuilt per clone rather
// than committed. Chained into the root `prepare` script, so `pnpm install` is
// enough; re-run directly with `pnpm agents:generate-subagents`.
//
// Idempotent. Prunes only files carrying the generated marker, so a personal
// agent dropped into .claude/agents by hand survives.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(repoRoot, '.agents/agents');

const MARKER = 'Generated by bin/agents.generate-subagents.mjs';

// Keys every target receives. Everything else is namespaced under a target key
// and passed through verbatim, because the tools genuinely diverge rather than
// merely spelling the same thing differently: `tools` is a Claude Code
// allowlist with no Codex equivalent, and Codex restricts a subagent through
// `sandbox_mode` instead. Inventing a neutral spelling would hide that.
const SHARED_KEYS = ['name', 'description'];
const TARGET_KEYS = ['claude', 'codex'];

const unquote = (value) => {
  const quoted = /^(['"])([\s\S]*)\1$/.exec(value);

  return quoted ? quoted[2] : value;
};

const pick = (source, keys) => Object.fromEntries(keys.filter((key) => key in source).map((key) => [key, source[key]]));

// A deliberately small YAML subset: single-line `key: value` scalars, plus one
// level of indentation under a bare `key:` for the per-target tables. No arrays,
// no folded scalars, no anchors. Adding a YAML dependency to parse three files
// would be the speculative abstraction code-design.md rules out; if the format
// outgrows this, take the dependency then.
const parseSource = (file, raw) => {
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(raw);

  if (!frontmatter) {
    throw new Error(`${file}: missing YAML frontmatter`);
  }

  const meta = {};
  let target = null;

  frontmatter[1].split(/\r?\n/).forEach((line, index) => {
    if (!line.trim() || line.trimStart().startsWith('#')) {
      return;
    }

    const nested = /^ {2}([\w-]+):[ \t]*(.+)$/.exec(line);

    if (nested) {
      if (!target) {
        throw new Error(`${file}: line ${index + 1} is indented under no key`);
      }

      target[nested[1]] = unquote(nested[2].trim());

      return;
    }

    const top = /^([\w-]+):[ \t]*(.*)$/.exec(line);

    if (!top) {
      throw new Error(`${file}: line ${index + 1} is not \`key: value\`; see docs/repository/subagents.md`);
    }

    if (top[2] === '') {
      target = {};
      meta[top[1]] = target;

      return;
    }

    meta[top[1]] = unquote(top[2].trim());
    target = null;
  });

  return { body: raw.slice(frontmatter[0].length).trim(), meta };
};

const validate = (file, meta) => {
  SHARED_KEYS.forEach((key) => {
    if (typeof meta[key] !== 'string' || !meta[key].trim()) {
      throw new Error(`${file}: \`${key}\` is required and must be a single-line string`);
    }
  });

  Object.keys(meta).forEach((key) => {
    if (!SHARED_KEYS.includes(key) && !TARGET_KEYS.includes(key)) {
      throw new Error(
        `${file}: unknown key \`${key}\`; expected one of ${[...SHARED_KEYS, ...TARGET_KEYS].join(', ')}`,
      );
    }
  });
};

// Every scalar is emitted double-quoted. A YAML double-quoted scalar is exactly
// JSON string syntax, so this is correct for any description -- including ones
// carrying a colon, which is the case a bare scalar silently misparses.
const renderClaude = (source, meta, body) => {
  const fields = { ...pick(meta, SHARED_KEYS), ...(meta.claude ?? {}) };
  const lines = Object.entries(fields).map(([key, value]) => `${key}: ${JSON.stringify(value)}`);

  return `---\n# ${MARKER} from .agents/agents/${source}. Do not edit.\n${lines.join('\n')}\n---\n\n${body}\n`;
};

const tomlScalar = (value) =>
  /^(true|false|-?\d+(\.\d+)?)$/.test(value) ? value : `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const renderCodex = (source, meta, body) => {
  // A TOML multi-line literal string processes no escapes, which is what prose
  // full of backslashes and quotes needs -- but it has no escape for its own
  // delimiter either.
  if (body.includes("'''")) {
    throw new Error(`${source}: body contains ''', which cannot be placed in a TOML literal string`);
  }

  const fields = { ...pick(meta, SHARED_KEYS), ...(meta.codex ?? {}) };
  const lines = Object.entries(fields).map(([key, value]) => `${key} = ${tomlScalar(value)}`);

  return `# ${MARKER} from .agents/agents/${source}. Do not edit.\n${lines.join('\n')}\n\ndeveloper_instructions = '''\n${body}\n'''\n`;
};

const prune = (dir) => {
  let entries;

  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }

  entries.forEach((entry) => {
    const path = join(dir, entry.name);

    if (entry.isFile() && readFileSync(path, 'utf8').includes(MARKER)) {
      rmSync(path);
    }
  });
};

const main = () => {
  let sources;

  try {
    sources = readdirSync(sourceDir)
      .filter((entry) => entry.endsWith('.md'))
      .sort();
  } catch {
    console.log('agents:generate-subagents — no .agents/agents directory; nothing to do.');

    return;
  }

  const targets = [
    { dir: join(repoRoot, '.claude/agents'), ext: '.md', render: renderClaude },
    { dir: join(repoRoot, '.codex/agents'), ext: '.toml', render: renderCodex },
  ];

  targets.forEach((target) => {
    prune(target.dir);
    mkdirSync(target.dir, { recursive: true });
  });

  sources.forEach((source) => {
    const { body, meta } = parseSource(source, readFileSync(join(sourceDir, source), 'utf8'));

    validate(source, meta);

    targets.forEach((target) => {
      writeFileSync(join(target.dir, `${meta.name}${target.ext}`), target.render(source, meta, body));
    });
  });

  console.log(`agents:generate-subagents — ${sources.length} agent(s) -> .claude/agents, .codex/agents`);
};

main();
